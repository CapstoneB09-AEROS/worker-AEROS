const supabase = require('../config/supabaseClient');
const { signedCommand, signedWindowCommand, verifyCommandAck } = require('./securityService');
const { assertActiveDevice } = require('./deviceRegistry');

const recentlyPublished = new Map();
const RETRY_MS = 15000;

function actionFromRow(row) {
  if (!row || row.execution_status !== 'pending' || !row.command_id ||
      !row.alert_id || !row.device_id || row.received_at) return null;
  if (row.window_action === 'open' && !row.buzzer_state) return 'WINDOW_OPEN';
  if (row.window_action === 'closed' && !row.buzzer_state) return 'WINDOW_CLOSE';
  if (row.buzzer_state === 'off' && !row.window_action && row.trigger_source === 'manual') {
    return 'MUTE_BUZZER';
  }
  return null;
}

async function publishPendingCommand(client, row) {
  if (!client.connected || !row || row.execution_status !== 'pending') return;
  const action = actionFromRow(row);
  if (!action || !['manual', 'auto'].includes(row.trigger_source)) {
    console.warn('[COMMAND] Invalid pending row:', row?.id);
    return;
  }
  const lastAttempt = recentlyPublished.get(row.command_id) || 0;
  if (Date.now() - lastAttempt < RETRY_MS) return;
  recentlyPublished.set(row.command_id, Date.now());
  try {
    await assertActiveDevice(row.device_id);
    const { data: alert, error } = await supabase.from('alert_logs')
      .select('id,device_id,resolved_at').eq('id', row.alert_id).maybeSingle();
    if (error || !alert || alert.device_id !== row.device_id || alert.resolved_at) {
      throw new Error('Alert tidak ada, sudah selesai, atau bukan milik perangkat');
    }
    const { data: state, error: stateError } = await supabase.from('device_state')
      .select('active_alert_id').eq('device_id', row.device_id).maybeSingle();
    if (stateError || !state || state.active_alert_id !== row.alert_id) {
      throw new Error('Perintah hanya boleh untuk alert gas yang sedang aktif');
    }
    // Contract: alert_logs.id is the UUID generated by the ESP32 as event_id.
    const issuedAt = Math.floor(Date.now() / 1000);
    const signed = action === 'MUTE_BUZZER'
      ? signedCommand(row.device_id, row.command_id, row.alert_id, issuedAt)
      : signedWindowCommand(row.device_id, row.command_id, row.alert_id, action, issuedAt);
    client.publish('aeros/' + row.device_id + '/cmd', JSON.stringify(signed),
      { qos: 1, retain: false }, (err) => {
        if (err) console.error('[COMMAND PUBLISH]', err.message);
        else console.log('[COMMAND SENT]', row.device_id, row.command_id);
      });
  } catch (err) {
    console.error('[COMMAND BLOCKED]', row.command_id, err.message);
    // Keep pending, so a newly registered/reconnected device can be retried.
  }
}

async function reconcilePendingCommands(client) {
  if (!client.connected) return;
  const { data, error } = await supabase.from('actuator_logs')
    .select('id,device_id,command_id,alert_id,buzzer_state,window_action,trigger_source,execution_status,received_at')
    .eq('execution_status', 'pending').is('received_at', null)
    .order('created_at', { ascending: true }).limit(100);
  if (error) return console.error('[COMMAND QUERY]', error.message);
  for (const row of data) await publishPendingCommand(client, row);
}

async function handleCommandAck(raw, topicDeviceId) {
  try {
    const p = verifyCommandAck(JSON.parse(raw.toString('utf8')));
    if (p.device_id !== topicDeviceId) throw new Error('device_id tidak cocok dengan topik ACK');
    await assertActiveDevice(p.device_id);
    const { data: row, error } = await supabase.from('actuator_logs')
      .select('command_id,alert_id,device_id,execution_status,window_action,buzzer_state,received_at,trigger_source')
      .eq('command_id', p.command_id).maybeSingle();
    if (error || !row || row.alert_id !== p.alert_id || row.device_id !== p.device_id) {
      throw new Error('ACK untuk command yang tidak dikenal');
    }
    const expectedAction = actionFromRow({ ...row, received_at: null });
    if ((p.version === 3 && p.action !== expectedAction) ||
        (p.version === 2 && expectedAction !== 'MUTE_BUZZER')) {
      throw new Error('ACK action tidak cocok dengan command database');
    }
    if (p.version === 3 && p.result === 'received') {
      // The motor/driver is not configured. DO NOT mark hardware execution successful.
      if (row.execution_status !== 'pending') return;
      const result = await supabase.from('actuator_logs')
        .update({ received_at: new Date().toISOString() })
        .eq('command_id', p.command_id).eq('execution_status', 'pending');
      if (result.error) throw result.error;
      recentlyPublished.delete(p.command_id);
      console.log('[WINDOW RECEIVED, NOT EXECUTED]', p.device_id, p.command_id);
      return;
    }
    if (row.execution_status === 'failed' ||
        (row.execution_status === 'success' && p.result !== 'success')) return;
    if (row.execution_status === 'pending') {
      const next = await supabase.from('actuator_logs')
        .update({ execution_status: p.result })
        .eq('command_id', p.command_id).eq('execution_status', 'pending');
      if (next.error) throw next.error;
    }
    recentlyPublished.delete(p.command_id);
    if (p.result === 'success') {
      const stamp = new Date().toISOString();
      const alert = await supabase.from('alert_logs').update({ acknowledged_at: stamp })
        .eq('id', p.alert_id).eq('device_id', p.device_id).is('resolved_at', null);
      if (alert.error) throw alert.error;
      const state = await supabase.from('device_state')
        .update({ ack_driver: true, ack_at: stamp, buzzer_state: 'off', updated_at: stamp })
        .eq('device_id', p.device_id).eq('active_alert_id', p.alert_id);
      if (state.error) throw state.error;
    }
    console.log('[COMMAND ACK]', p.device_id, p.command_id, p.result);
  } catch (err) {
    console.warn('[COMMAND ACK REJECTED]', err.message);
  }
}
module.exports = { publishPendingCommand, reconcilePendingCommands, handleCommandAck, actionFromRow };

